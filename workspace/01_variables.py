# --- Integers ---
age = 16
print("Age:", age)

# --- Floats ---
gpa = 3.75
print("GPA:", gpa)

# --- Strings ---
name = "Alex"
print("Name:", name)

# --- Booleans ---
is_enrolled = True
print("Enrolled:", is_enrolled)

# --- Type checking ---
print(type(age))
print(type(gpa))
print(type(name))
print(type(is_enrolled))

